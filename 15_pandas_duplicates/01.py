# Пропуски
# В pandas пропущенные значения могут представляться как NaN, None или NaT — в зависимости от типа данных.

# Основные методы:
# df.isna()          # Проверка пропусков
# df.isna().sum()    # Количество пропусков по столбцам
# df.dropna()        # Удаление строк с пропусками
# df.fillna(0)       # Заполнение пропусков нулями

import pandas as pd

df = pd.DataFrame({
    "product": ["A", "B", "C"],
    "quantity": [10, None, 5],
})

print(df.isna().sum())


