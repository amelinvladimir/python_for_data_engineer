# В первом видео мы изучали отдельные признаки: распределение выручки, суммы заказов, частоту категорий.

# Но бизнес-вопросы чаще требуют анализа нескольких признаков одновременно.

# Например:
# - Есть ли связь между размером скидки и суммой заказа?
# - Отличается ли средний чек у новых и постоянных клиентов?
# - Какие категории товаров чаще покупают крупные клиенты?
# - Связано ли количество товаров в заказе с его выручкой?
# Для этого используется двумерный и многомерный анализ.


# Рассмотрим пример:
import pandas as pd

df = pd.DataFrame({
    "quantity": [1, 2, 3, 4, 5],
    "revenue": [100, 200, 300, 400, 500],
    "discount": [0, 0, 5, 10, 15]
})

# Мы можем проверить, как количество товаров связано с выручкой.
print(df[["discount", "revenue"]].corr())

# Корреляция
# Корреляция — статистическая мера силы и направления линейной взаимосвязи между двумя числовыми признаками.

# Коэффициент корреляции Пирсона находится в диапазоне от -1 до 1.
# Значение	Интерпретация
# Близко к 1	Сильная положительная линейная связь
# Близко к -1	Сильная отрицательная линейная связь
# Близко к 0	Слабая линейная связь или её отсутствие

# Например:
# - чем больше товаров в заказе, тем выше выручка — возможна положительная корреляция;
# - чем больше скидка, тем меньше итоговая выручка с единицы товара — возможна отрицательная корреляция;
# - между номером заказа и суммой покупки может не быть линейной связи.

# Важное ограничение: корреляция не означает причинно-следственную связь.

# Если мы обнаружили, что клиенты с большими скидками тратят больше, это ещё не доказывает, 
# что именно скидка заставляет их покупать больше. 
# Возможно, большие скидки предоставляются клиентам, которые и без этого совершают крупные покупки.