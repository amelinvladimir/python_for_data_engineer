# Описательная статистика
# Рассмотрим столбец с суммами заказов

import pandas as pd

revenue = pd.Series([100, 150, 200, 250, 1300])

print(revenue.mean())
print(revenue.median())
print(revenue.std())
print(revenue.min())
print(revenue.max())

# В нашем примере среднее заметно выше медианы из-за одного крупного заказа.
# среднее не всегда хорошо описывает типичное наблюдение
# Например, если мы хотим понять, сколько обычно тратит покупатель, медиана иногда оказывается полезнее среднего.