# Одних чисел часто недостаточно. Нужно посмотреть, как распределены значения.

# Например, средняя сумма заказа может быть 500 рублей, но это не означает, что большинство заказов находится около 500 рублей.

# Для визуализации используем Matplotlib и Seaborn.
# Matplotlib — библиотека для построения графиков с широкими возможностями настройки.
# Seaborn — библиотека, построенная поверх Matplotlib, которая упрощает создание статистических визуализаций.

# Установить библиотеки:
# pip install matplotlib seaborn

import matplotlib.pyplot as plt
import seaborn as sns
import pandas as pd

df = pd.read_csv("order_items_raw.csv")
sns.histplot(data=df, x="revenue", bins=20)

plt.title("Распределение выручки заказов")
plt.xlabel("Выручка")
plt.ylabel("Количество заказов")
plt.show()

# Гистограмма
# Показывает распределение числового признака.

# Гистограмма помогает увидеть:
# - симметрично ли распределены значения;
# - есть ли длинный хвост;
# - наблюдается ли несколько пиков;
# - есть ли подозрительно большие или маленькие значения.