# Объединение таблиц
# В аналитике данные часто хранятся в нескольких таблицах. Например, таблица заказов содержит идентификатор клиента, но не содержит его город или имя.

import pandas as pd

orders = pd.DataFrame({
    "order_id": [101, 102, 103, 104],
    "customer_id": [1, 2, 1, 4],
    "amount": [5000, 3000, 7000, 2000]
})

customers = pd.DataFrame({
    "customer_id": [1, 2, 3],
    "name": ["Анна", "Борис", "Вера"],
    "city": ["Москва", "Тверь", "Казань"]
})

# Чтобы получить заказы вместе с именами и городами клиентов, необходимо объединить две таблицы по customer_id.

result = orders.merge(
    customers,
    on="customer_id",
    how="left"
)

print(result)

# merge() сопоставляет строки двух таблиц по ключу и добавляет подходящие столбцы.