import numpy as np

orders = np.array([
    12500,
    3400,
    27800,
    9100,
    45200,
    6700,
    18300,
    5200,
    31400,
    8900
])

# Это выборка заказов интернет-магазина.
# Нам нужно ответить на вопросы бизнеса.

# Выручка
revenue = orders.sum()
print(revenue)

# Средний чек
average_order = orders.mean()
print(average_order)

# Минимальный заказ
print(orders.min())

# Максимальный заказ
print(orders.max())

# Стандартное отклонение
print(orders.std())

# Стандартное отклонение показывает, 
# насколько значения в среднем разбросаны относительно среднего.