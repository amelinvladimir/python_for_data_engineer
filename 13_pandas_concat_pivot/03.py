# pivot_table() — сводная таблица с агрегацией

import pandas as pd

sales = pd.DataFrame({
    "city": ["Москва", "Москва", "Москва", "Тверь"],
    "month": ["Январь", "Январь", "Февраль", "Январь"],
    "revenue": [60000, 40000, 120000, 40000]
})

# Если за месяц у города может быть много записей, используем pivot_table()

table = sales.pivot_table(
    index="city",
    columns="month",
    values="revenue",
    aggfunc="sum",
    fill_value=0
)

print(table)

# Теперь две январские записи Москвы объединятся в одну сумму — 100 000.

# Параметр	        Назначение
# index	            Строки сводной таблицы
# columns	            Столбцы сводной таблицы
# values	            Рассчитываемый показатель
# aggfunc	            Функция агрегации: sum, mean, count и другие
# fill_value	        Значение для пустых ячеек результата

# Различие простое: pivot() перестраивает уникальные комбинации, а pivot_table() умеет агрегировать повторяющиеся комбинации.

