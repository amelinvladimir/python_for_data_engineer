
import numpy as np

orders = np.array([
    12500,
    3400,
    27800,
    9100,
    45200,
    6700,
    18300,
    5200,
    31400,
    8900
])

print("Количество заказов:", orders.size)
print("Выручка:", orders.sum())
print("Средний чек:", orders.mean())
print("Крупных заказов:", (orders > 10_000).sum())

